-- IMPORTANTE: raw_* preserva todas as colunas dos quatro CSVs, em VARCHAR.
-- Nenhuma RAW tem PK, FK, UNIQUE, NOT NULL ou CHECK.

CREATE TABLE IF NOT EXISTS raw_viagem (
    id_viagem VARCHAR, num_proposta VARCHAR, situacao VARCHAR,
    viagem_urgente VARCHAR, justificativa_urgencia VARCHAR,
    cod_orgao_superior VARCHAR, nome_orgao_superior VARCHAR,
    cod_orgao_solicitante VARCHAR, nome_orgao_solicitante VARCHAR,
    cpf_viajante VARCHAR, nome_viajante VARCHAR, cargo VARCHAR,
    funcao VARCHAR, descricao_funcao VARCHAR, data_inicio VARCHAR,
    data_fim VARCHAR, destinos VARCHAR, motivo VARCHAR,
    valor_diarias VARCHAR, valor_passagens VARCHAR,
    valor_devolucao VARCHAR, valor_outros_gastos VARCHAR
);

CREATE TABLE IF NOT EXISTS raw_pagamento (
    id_viagem VARCHAR, num_proposta VARCHAR, cod_orgao_superior VARCHAR,
    nome_orgao_superior VARCHAR, cod_orgao_pagador VARCHAR,
    nome_orgao_pagador VARCHAR, cod_ug_pagadora VARCHAR,
    nome_ug_pagadora VARCHAR, tipo_pagamento VARCHAR, valor VARCHAR
);

CREATE TABLE IF NOT EXISTS raw_passagem (
    id_viagem VARCHAR, num_proposta VARCHAR, meio_transporte VARCHAR,
    pais_origem_ida VARCHAR, uf_origem_ida VARCHAR,
    cidade_origem_ida VARCHAR, pais_destino_ida VARCHAR,
    uf_destino_ida VARCHAR, cidade_destino_ida VARCHAR,
    pais_origem_volta VARCHAR, uf_origem_volta VARCHAR,
    cidade_origem_volta VARCHAR, pais_destino_volta VARCHAR,
    uf_destino_volta VARCHAR, cidade_destino_volta VARCHAR,
    valor_passagem VARCHAR, taxa_servico VARCHAR,
    data_emissao VARCHAR, hora_emissao VARCHAR
);

CREATE TABLE IF NOT EXISTS raw_trecho (
    id_viagem VARCHAR, num_proposta VARCHAR, sequencia_trecho VARCHAR,
    origem_data VARCHAR, origem_pais VARCHAR, origem_uf VARCHAR,
    origem_cidade VARCHAR, destino_data VARCHAR, destino_pais VARCHAR,
    destino_uf VARCHAR, destino_cidade VARCHAR, meio_transporte VARCHAR,
    numero_diarias VARCHAR, missao VARCHAR
);

-- SILVER: 4 PKs + 3 FKs + 8 restricoes adicionais exigidas no projeto.
CREATE TABLE IF NOT EXISTS silver_viagem (
    id_viagem VARCHAR(20) PRIMARY KEY,
    num_proposta VARCHAR(20),
    situacao VARCHAR(50),
    viagem_urgente VARCHAR(5),
    cod_orgao_superior VARCHAR(20),
    nome_orgao_superior VARCHAR(255) NOT NULL, -- Restricao extra 1
    nome_viajante VARCHAR(255),
    cargo VARCHAR(255),
    data_inicio DATE,
    data_fim DATE,
    destinos VARCHAR(4000),
    motivo VARCHAR(4000),
    valor_diarias NUMERIC(10,2) CHECK (valor_diarias >= 0), -- Extra 2
    valor_passagens NUMERIC(10,2),
    valor_devolucao NUMERIC(10,2),
    valor_outros_gastos NUMERIC(10,2),
    valor_total NUMERIC(12,2),
    duracao_dias INTEGER
);

CREATE TABLE IF NOT EXISTS silver_pagamento (
    id_pagamento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_viagem VARCHAR(20) NOT NULL REFERENCES silver_viagem(id_viagem),
    num_proposta VARCHAR(20),
    nome_orgao_pagador VARCHAR(255),
    nome_ug_pagadora VARCHAR(255),
    tipo_pagamento VARCHAR(50) NOT NULL, -- Extra 1
    valor NUMERIC(10,2) CHECK (valor >= 0) -- Extra 2
);

CREATE TABLE IF NOT EXISTS silver_passagem (
    id_passagem INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_viagem VARCHAR(20) NOT NULL REFERENCES silver_viagem(id_viagem),
    meio_transporte VARCHAR(50),
    pais_origem_ida VARCHAR(60),
    uf_origem_ida VARCHAR(40),
    cidade_origem_ida VARCHAR(80),
    pais_destino_ida VARCHAR(60),
    uf_destino_ida VARCHAR(40),
    cidade_destino_ida VARCHAR(80),
    valor_passagem NUMERIC(10,2) CHECK (valor_passagem >= 0), -- Extra 1
    taxa_servico NUMERIC(10,2) CHECK (taxa_servico >= 0), -- Extra 2
    data_emissao DATE
);

CREATE TABLE IF NOT EXISTS silver_trecho (
    id_trecho INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_viagem VARCHAR(20) NOT NULL REFERENCES silver_viagem(id_viagem),
    sequencia_trecho INTEGER,
    origem_data DATE,
    origem_uf VARCHAR(40),
    origem_cidade VARCHAR(80),
    destino_data DATE,
    destino_uf VARCHAR(40),
    destino_cidade VARCHAR(80),
    meio_transporte VARCHAR(50),
    numero_diarias NUMERIC(10,2) CHECK (numero_diarias >= 0), -- Extra 1
    CONSTRAINT uq_viagem_sequencia UNIQUE (id_viagem, sequencia_trecho) -- Extra 2
);

-- Indices para acelerar consultas JOIN/WHERE sobre as chaves estrangeiras.
CREATE INDEX IF NOT EXISTS idx_pagamento_viagem ON silver_pagamento(id_viagem);
CREATE INDEX IF NOT EXISTS idx_passagem_viagem ON silver_passagem(id_viagem);
CREATE INDEX IF NOT EXISTS idx_trecho_viagem ON silver_trecho(id_viagem);
